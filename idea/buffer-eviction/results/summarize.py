#!/usr/bin/env python3
"""Aggregate per-run results (output of bench/collect.py) for reports.

usage: summarize.py runs.csv OUT_PREFIX
writes OUT_PREFIX-summary.csv  (one row per workload x shared_buffers x policy)
       OUT_PREFIX-tables.md    (miss-ratio / throughput / p99 tables, vs clock)
Stdlib only (no pandas on the bench machine or laptop).
"""
import csv
import statistics as st
import sys
from collections import defaultdict

POLICIES = ["clock", "srrip", "brrip", "drrip", "sieve", "s3fifo"]
WORKLOADS = ["tpcc", "ycsb-b", "ycsb-e", "tpch"]
SIZES = [128, 256, 512, 1024]


def num(v):
    return float(v) if v not in ("", None) else float("nan")


def main():
    runs = list(csv.DictReader(open(sys.argv[1])))
    prefix = sys.argv[2]
    groups = defaultdict(list)
    for r in runs:
        groups[(r["workload"], int(r["sb_mb"]), r["policy"])].append(r)

    agg = {}
    for key, g in groups.items():
        miss = [100 * (1 - num(r["hit_ratio"])) for r in g]
        tps = [num(r["throughput"]) for r in g]
        agg[key] = {
            "workload": key[0], "sb_mb": key[1], "policy": key[2], "reps": len(g),
            "miss_pct": st.mean(miss), "miss_pct_range": max(miss) - min(miss),
            "throughput": st.mean(tps),
            "throughput_spread_pct": (max(tps) / min(tps) - 1) * 100,
            "lat_p50_ms": st.mean(num(r["lat_p50_us"]) for r in g) / 1000,
            "lat_p99_ms": st.mean(num(r["lat_p99_us"]) for r in g) / 1000,
            "io_reads": st.mean(num(r["io_reads"]) for r in g),
            "checks_per_alloc": st.mean(num(r["checks_per_alloc"]) for r in g),
            "policy_lock_wait_pct": 100 * st.mean(num(r["policy_lock_wait_frac"]) for r in g),
            "io_wait_pct": 100 * st.mean(num(r["io_wait_frac"]) for r in g),
        }
    for (wl, sb, _), a in agg.items():
        base = agg.get((wl, sb, "clock"))
        a["miss_vs_clock_pct"] = (a["miss_pct"] / base["miss_pct"] - 1) * 100 if base else ""
        a["tps_vs_clock_pct"] = (a["throughput"] / base["throughput"] - 1) * 100 if base else ""

    rows = sorted(agg.values(), key=lambda a: (WORKLOADS.index(a["workload"]), a["sb_mb"],
                                               POLICIES.index(a["policy"])))
    with open(prefix + "-summary.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        for a in rows:
            w.writerow({k: round(v, 4) if isinstance(v, float) else v for k, v in a.items()})

    def table(title, field, fmt, note=""):
        out = [f"### {title}", ""]
        if note:
            out += [note, ""]
        out.append("| workload | sb | " + " | ".join(POLICIES) + " |")
        out.append("|---|---|" + "---|" * len(POLICIES))
        for wl in WORKLOADS:
            for sb in SIZES:
                cells = []
                vals = {p: agg[(wl, sb, p)][field] for p in POLICIES
                        if (wl, sb, p) in agg and agg[(wl, sb, p)][field] != ""}
                if not vals:
                    continue
                best = min(vals.values()) if field != "throughput" else max(vals.values())
                for p in POLICIES:
                    if p not in vals:
                        cells.append("–")
                        continue
                    s = fmt.format(vals[p])
                    cells.append(f"**{s}**" if vals[p] == best and len(vals) > 1 else s)
                sbs = f"{sb // 1024}GB" if sb >= 1024 else f"{sb}MB"
                out.append(f"| {wl} | {sbs} | " + " | ".join(cells) + " |")
        return "\n".join(out) + "\n"

    with open(prefix + "-tables.md", "w") as f:
        f.write("<!-- generated by summarize.py; best value per row in bold; – = run missing -->\n\n")
        f.write(table("Buffer miss ratio (%)", "miss_pct", "{:.2f}",
                      "1 - blks_hit/(blks_hit+blks_read) from pg_stat_database; direct I/O, so every miss is an SSD read."))
        f.write("\n" + table("Miss ratio vs clock (%)", "miss_vs_clock_pct", "{:+.1f}", "Negative = fewer misses than clock."))
        f.write("\n" + table("Throughput (req/s)", "throughput", "{:.1f}",
                             "Noisy between reps (see throughput_spread_pct in the summary CSV); TPC-H is queries/s."))
        f.write("\n" + table("p99 latency (ms)", "lat_p99_ms", "{:.1f}"))
        f.write("\n" + table("Buffers inspected per eviction", "checks_per_alloc", "{:.2f}"))
        wins = defaultdict(int)
        for wl in WORKLOADS:
            for sb in SIZES:
                vals = {p: agg[(wl, sb, p)]["miss_pct"] for p in POLICIES if (wl, sb, p) in agg}
                if len(vals) == len(POLICIES):
                    wins[min(vals, key=vals.get)] += 1
        f.write("\n### Lowest miss ratio count (complete rows only)\n\n| policy | wins |\n|---|---|\n")
        for p in POLICIES:
            f.write(f"| {p} | {wins[p]} |\n")


if __name__ == "__main__":
    main()
